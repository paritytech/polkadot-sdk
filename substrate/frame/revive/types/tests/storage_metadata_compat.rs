impl<New> EncodingRoundtrip<New>
where
	New: PartialEq + Debug,
{
	fn assert_matches(self) {
		assert_eq!(self.new_bytes, self.old_bytes);
		assert_eq!(self.decoded_new, self.new);
		assert_eq!(self.reencoded_old, self.old_bytes);
	}
}

fn encoding_roundtrip<New, Old>(new: New, old: Old) -> EncodingRoundtrip<New>
where
	New: Decode + Encode,
	Old: Decode + Encode,
{
	let new_bytes = new.encode();
	let old_bytes = old.encode();
	let decoded_new = New::decode(&mut &old_bytes[..]).unwrap();
	let reencoded_old = Old::decode(&mut &new_bytes[..]).unwrap().encode();

	EncodingRoundtrip { new, new_bytes, old_bytes, decoded_new, reencoded_old }
}

