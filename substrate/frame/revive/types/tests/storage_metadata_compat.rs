//! Verifies that each client-facing storage type in `pallet-revive-types` preserves the SCALE
//! encoding that existed before storage versioning was introduced.
//!
//! The old side of each metadata assertion is generated by `subxt` from the checked-in
//! `pre-storage-versioning-metadata.scale` file emitted by `revive-dev-runtime` before the
//! storage wrappers were added. Each test builds one new versioned type and the matching old
//! metadata type, then checks that both values encode to identical bytes and decode across the type
//! boundary.
//!
//! `CodeInfoV1` predates the metadata snapshot used here, so that one check uses a local legacy
//! struct with the same fields and compact encoding that the historical runtime used.
//!
//! These tests are intentionally one-type-per-test so compatibility regressions point at the exact
//! layout that moved. They protect migrations, RPC helpers, and off-chain clients from silent
//! storage decoding drift when names, wrappers, or field definitions change.

