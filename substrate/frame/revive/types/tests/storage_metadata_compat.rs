/// Creates one representative value for a compatibility test type.
trait Sample {
	/// Returns a deterministic value whose old and new layouts should encode identically.
	fn sample() -> Self;

	/// Returns a deterministic value derived from `seed` when the test needs distinct values.
	fn seeded_sample(_seed: u8) -> Self
	where
		Self: Sized,
	{
		Self::sample()
	}
}

