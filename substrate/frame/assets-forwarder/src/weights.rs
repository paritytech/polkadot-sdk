use frame_support::{traits::Get, weights::{Weight, constants::RocksDbWeight}};
use core::marker::PhantomData;

/// Weight functions needed for `pallet_assets_forwarder`.
pub trait WeightInfo {
	fn forward_asset() -> Weight;
	fn sync_asset_status() -> Weight;
	fn remove_forwarded_asset() -> Weight;
}

/// Weights for `pallet_assets_forwarder` using the Substrate node and recommended hardware.
pub struct SubstrateWeight<T>(PhantomData<T>);
impl<T: frame_system::Config> WeightInfo for SubstrateWeight<T> {
	fn forward_asset() -> Weight {
		Weight::from_parts(150_000_000, 6000)
			.saturating_add(T::DbWeight::get().reads(6_u64))
			.saturating_add(T::DbWeight::get().writes(4_u64))
	}
	fn sync_asset_status() -> Weight {
		Weight::from_parts(120_000_000, 6000)
			.saturating_add(T::DbWeight::get().reads(5_u64))
			.saturating_add(T::DbWeight::get().writes(2_u64))
	}
	fn remove_forwarded_asset() -> Weight {
		Weight::from_parts(60_000_000, 6000)
			.saturating_add(T::DbWeight::get().reads(3_u64))
			.saturating_add(T::DbWeight::get().writes(3_u64))
	}
}

