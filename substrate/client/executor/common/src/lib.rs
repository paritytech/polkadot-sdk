use sp_wasm_interface::{Function, ABI_EPOCH_LEGACY};
use std::collections::HashMap;

/// The allocation-side classification of a registered host function, derived from the
/// metadata generated by the `#[runtime_interface]` macro.
#[derive(Clone, Copy)]
enum AllocationSide {
	/// The function makes the host allocate guest memory (one of its marshalling strategies is
	/// `AllocateAndReturn*`), so it is only usable by runtimes relying on the host-side
	/// allocator.
	Host,
	/// The function belongs to an RFC-145 ABI epoch, so it is only meant to be used by
	/// runtimes managing their own heap.
	Runtime,
	/// The function never allocates guest memory and pre-dates the RFC-145 divide, so it is
	/// usable with either allocation scheme.
	Neutral,
	/// The function implementation doesn't provide the allocation metadata.
	Unknown,
}

/// Checks that a runtime only imports host functions that allocate either on the host or the
/// runtime side, but not both.
///
/// Mixing the two sides within one runtime means running two allocators over the same guest
/// heap, which is never correct; it can happen e.g. when a runtime links two different `sp-io`
/// versions, one from each side of the RFC-145 divide. The classification is derived from the
/// metadata of the registered host functions (see [`AllocationSide`]), so it covers all the
/// current and future host functions and versions without any hand-maintained list.
pub struct RuntimeAllocSanityChecker {
	/// Classification of the registered host functions by name.
	classes: HashMap<String, AllocationSide>,
	/// Bit 0 is set once a host-side-allocating import has been seen, bit 1 once a
	/// runtime-side-allocating one has been seen.
	sides: u8,
	/// `ext_*` imports that could not be classified.
	unclassified: Vec<String>,
}

impl RuntimeAllocSanityChecker {
	/// Creates a new checker classifying imports against the given registered host functions.
	pub fn new(host_functions: &[&'static dyn Function]) -> Self {
		let classes = host_functions
			.iter()
			.map(|function| {
				let side = match (function.host_allocates(), function.abi_epoch()) {
					(Some(true), _) => AllocationSide::Host,
					(Some(false), Some(epoch)) if epoch > ABI_EPOCH_LEGACY => {
						AllocationSide::Runtime
					},
					(Some(false), _) => AllocationSide::Neutral,
					(None, _) => AllocationSide::Unknown,
				};
				(function.name().to_string(), side)
			})
			.collect();
		Self { classes, sides: 0, unclassified: Vec::new() }
	}

	/// Checks a single function import.
	pub fn check(&mut self, name: &str) {
		// All the host functions generated by the `#[runtime_interface]` macro are named
		// `ext_<interface>_<function>_version_<n>`; other imports (e.g. hand-written
		// environment imports) are not covered by this check.
		if !name.starts_with("ext_") {
			return;
		}
		match self.classes.get(name) {
			Some(AllocationSide::Host) => self.sides |= 1,
			Some(AllocationSide::Runtime) => self.sides |= 2,
			Some(AllocationSide::Neutral) => (),
			Some(AllocationSide::Unknown) | None => self.unclassified.push(name.to_string()),
		}
	}

	/// Returns true if all the functions checked only allocate on the host side or only on the
	/// runtime side, but not both.
	pub fn check_result(&self) -> bool {
		self.sides < 3
	}

	/// Returns the names of the imported `ext_*` host functions that [`Self::check`] could not
	/// classify: they are either not registered with this executor at all, or their
	/// implementation doesn't provide the allocation metadata.
	///
	/// This is not necessarily a problem — a chain may legitimately define its own host
	/// functions — but such imports are not covered by the allocation-side consistency check,
	/// so the caller may want to surface them.
	pub fn unclassified_imports(&self) -> &[String] {
		&self.unclassified
	}
}
