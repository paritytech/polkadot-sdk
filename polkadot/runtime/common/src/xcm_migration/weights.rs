//! Weights of the stages of [`super::MigrateXcmToLatest`].

use frame_support::weights::{constants::RocksDbWeight, Weight};

/// Weight functions of a [`super::MigrationStage`], generated by the benchmarks in
/// [`super::benchmarking`].
pub trait WeightInfo {
	/// A step that finds no entry to upgrade.
	fn step_base() -> Weight;
	/// A step that upgrades a single, worst case entry.
	///
	/// Charged for every entry, on top of [`Self::step_base`] once per step.
	fn step_item() -> Weight;
}

/// Conservative weights for tests and runtimes that haven't run the benchmarks yet.
///
/// Production runtimes should use benchmarked weights.
impl WeightInfo for () {
	fn step_base() -> Weight {
		RocksDbWeight::get()
			.reads(1)
			.saturating_add(Weight::from_parts(10_000_000, 4_096))
	}
	fn step_item() -> Weight {
		RocksDbWeight::get()
			.reads_writes(3, 3)
			.saturating_add(Weight::from_parts(50_000_000, 16_384))
	}
}
