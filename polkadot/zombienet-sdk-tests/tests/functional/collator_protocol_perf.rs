//! Collator-protocol performance: the V2 baseline against the V4 stack, each measured on its own
//! elastic-scaling network.
//!
//! Two cells, run one at a time (they are separate networks — never concurrently, or the CPU
//! contention corrupts the numbers):
//! - `v2_rpo1`: classic collator protocol, V2 descriptors, relay parent offset 1
//!   (`elastic-scaling-rpo-1`, para 2900). The "before" baseline.
//! - `v4_rpo0`: `--experimental-collator-protocol`, V3 descriptors, relay parent offset 0
//!   (`elastic-scaling-v3`, para 2800). Run after the collator-side fixes land.
//!
//! Each cell spawns rococo-local with 6 validators and one parachain elastic-scaled to 3 cores
//! (lookahead 5, max_validators_per_core 2, group_rotation_frequency 4, libp2p everywhere), waits
//! for the first session change and the first backed candidate, then measures a 100-relay-block
//! window. Ranges are wide — this is a measurement, not a gate; the numbers are logged for a
//! side-by-side comparison.
//!
//! Five numbers, all deltas over the same window:
//! 1. backed candidates — `ParaInclusion.CandidateBacked` in finalized relay blocks; divided by
//!    `blocks × cores` this is core utilisation.
//! 2. parachain height gain — collator `substrate_block_height{status="finalized"}` is the progress
//!    number; `{status="best"}` is the canonical-chain denominator used in 3, since finality lags
//!    by a dozen parablocks.
//! 3. collations generated by the collator — `polkadot_parachain_collations_generated_total`, one
//!    increment per collation receipt, fresh or resubmitted. `generated / best_gain` is "collation
//!    attempts per canonical parablock" (1.0 is perfect). Together with the fresh blocks built
//!    (`substrate_proposer_block_constructed_count`) it splits into resubmissions (`generated
//!    - built`, V3 only) and orphaned blocks (`built - best_gain`, approximate).
//! 4. successful collation fetches, summed over validators —
//!    `polkadot_parachain_collation_requests_total{success="succeeded"}`; per backed candidate this
//!    is PoV transfers per useful candidate. Emitted by both validator-side implementations.
//! 5. candidates seconded, summed over validators —
//!    `polkadot_parachain_candidate_backing_candidates_seconded_total`; per backed candidate this
//!    is PVF executions per useful candidate.
//!
//! As the "why" when 1 and 4 disagree: collator `polkadot_parachain_collation_expired_count{state}`
//! — collations never fetched (`created`/`advertised`/`requested`) vs fetched but never backed
//! (`fetched`). Under-counts in V3, where a resubmission resets the tracker entry.
//!
//! Number 3 and the expiry counts are registered by the collator's *embedded relay-chain node*,
//! whose Prometheus endpoint zombienet does not scrape (`NetworkNode::reports` targets the
//! parachain side). They are read best-effort from the relay-side `--prometheus-port` zombienet
//! injects after the `--` separator in the collator's args, and reported as `n/a` if that
//! endpoint is unreachable (e.g. on non-native providers).
//!
//! Logging matches the resubmit suite (trace on the collator protocol) so the throughput numbers
//! stay comparable with the cells measured there.

