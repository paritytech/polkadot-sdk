//! Tests for the trait and dispatch implementation generated by `XcmWeightInfoTrait`.

use xcm::latest::{prelude::*, GetWeight};

#[derive(xcm_procedural::XcmWeightInfoTrait)]
pub enum MacroTestInstruction<Call> {
	ClearOrigin,
	WithdrawAsset(Assets),
	TransferAsset { assets: Assets, beneficiary: Location },
	SetAppendix(Xcm<Call>),
}

pub struct MacroTestWeightInfo;

impl<Call> XcmWeightInfo<Call> for MacroTestWeightInfo {
	fn clear_origin() -> Weight {
		Weight::from_parts(11, 11)
	}

	fn withdraw_asset(assets: &Assets) -> Weight {
		let value = if assets.len() == 0 { 101 } else { 102 };
		Weight::from_parts(value, value)
	}

	fn transfer_asset(assets: &Assets, beneficiary: &Location) -> Weight {
		let assets_value = if assets.len() == 0 { 0 } else { 10 };
		let beneficiary_value = if beneficiary == &Here.into() { 1 } else { 2 };
		let value = 200 + assets_value + beneficiary_value;
		Weight::from_parts(value, value)
	}

	fn set_appendix(xcm: &Xcm<Call>) -> Weight {
		let value = 300 + xcm.0.len() as u64;
		Weight::from_parts(value, value)
	}
}

#[test]
fn generated_dispatch_covers_all_variant_shapes() {
	fn assert_get_weight<T: GetWeight<MacroTestWeightInfo>>() {}
	assert_get_weight::<MacroTestInstruction<()>>();

	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::ClearOrigin),
		Weight::from_parts(11, 11),
	);

	let assets: Assets = (Here, 1u128).into();
	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::WithdrawAsset(
			assets,
		)),
		Weight::from_parts(102, 102),
	);

	let assets: Assets = (Here, 1u128).into();
	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::TransferAsset {
			assets,
			beneficiary: Here.into(),
		}),
		Weight::from_parts(211, 211),
	);

	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::SetAppendix(Xcm(
			vec![ClearOrigin],
		))),
		Weight::from_parts(301, 301),
	);
}

mod generic_name_collisions {
	use xcm::latest::{prelude::*, GetWeight};

	#[derive(xcm_procedural::XcmWeightInfoTrait)]
	pub enum GenericInstruction<W, W1> {
		ClearOrigin,
		SetAppendix(Xcm<(W, W1)>),
	}

	pub struct GenericWeightInfo;

	impl<W, W1> XcmWeightInfo<W, W1> for GenericWeightInfo {
		fn clear_origin() -> Weight {
			Weight::from_parts(1, 1)
		}

		fn set_appendix(_xcm: &Xcm<(W, W1)>) -> Weight {
			Weight::from_parts(2, 2)
		}
	}

	#[test]
	fn generated_dispatch_uses_an_available_provider_name() {
		fn assert_get_weight<T: GetWeight<GenericWeightInfo>>() {}
		assert_get_weight::<GenericInstruction<(), ()>>();

		assert_eq!(
			GetWeight::<GenericWeightInfo>::weight(&GenericInstruction::<(), ()>::ClearOrigin),
			Weight::from_parts(1, 1),
		);
		assert_eq!(
			GetWeight::<GenericWeightInfo>::weight(&GenericInstruction::<(), ()>::SetAppendix(
				Xcm(vec![ClearOrigin],)
			)),
			Weight::from_parts(2, 2),
		);
	}
}
