//! Test the methods generated by the Builder derive macro.
//! Tests directly on the actual Xcm struct and Instruction enum.

use frame_support::BoundedVec;
use xcm::latest::{prelude::*, GetWeight};

#[derive(xcm_procedural::XcmWeightInfoTrait)]
pub enum MacroTestInstruction<Call> {
	ClearOrigin,
	WithdrawAsset(Assets),
	TransferAsset { assets: Assets, beneficiary: Location },
	SetAppendix(Xcm<Call>),
}

pub struct MacroTestWeightInfo;

impl<Call> XcmWeightInfo<Call> for MacroTestWeightInfo {
	fn clear_origin() -> Weight {
		Weight::from_parts(11, 11)
	}

	fn withdraw_asset(assets: &Assets) -> Weight {
		let id = if assets.len() == 0 { 101 } else { 102 };
		Weight::from_parts(id, id)
	}

	fn transfer_asset(assets: &Assets, beneficiary: &Location) -> Weight {
		let assets_tag = if assets.len() == 0 { 0 } else { 10 };
		let beneficiary_tag = if beneficiary == &Here.into() { 1 } else { 2 };
		let id = 200 + assets_tag + beneficiary_tag;
		Weight::from_parts(id, id)
	}

	fn set_appendix(xcm: &Xcm<Call>) -> Weight {
		let id = 300 + xcm.0.len() as u64;
		Weight::from_parts(id, id)
	}
}

mod generic_w_name_collision {
	use xcm::latest::{prelude::*, GetWeight};

	#[derive(xcm_procedural::XcmWeightInfoTrait)]
	pub enum GenericWInstruction<W> {
		ClearOrigin,
		SetAppendix(Xcm<W>),
	}

	pub struct GenericWWeightInfo;

	impl<W> XcmWeightInfo<W> for GenericWWeightInfo {
		fn clear_origin() -> Weight {
			Weight::from_parts(1, 1)
		}

		fn set_appendix(_xcm: &Xcm<W>) -> Weight {
			Weight::from_parts(2, 2)
		}
	}

	#[test]
	fn generated_dispatch_handles_enum_with_generic_named_w() {
		fn assert_get_weight_impl<T: GetWeight<GenericWWeightInfo>>() {}
		assert_get_weight_impl::<GenericWInstruction<()>>();

		assert_eq!(
			GetWeight::<GenericWWeightInfo>::weight(&GenericWInstruction::<()>::ClearOrigin),
			Weight::from_parts(1, 1)
		);
		assert_eq!(
			GetWeight::<GenericWWeightInfo>::weight(&GenericWInstruction::<()>::SetAppendix(Xcm(
				vec![ClearOrigin],
			))),
			Weight::from_parts(2, 2)
		);
	}
}

#[test]
fn builder_pattern_works() {
	let asset: Asset = (Here, 100u128).into();
	let beneficiary: Location = [0u8; 32].into();
	let message: Xcm<()> = Xcm::builder()
		.receive_teleported_asset(asset.clone())
		.buy_execution(asset.clone(), Unlimited)
		.deposit_asset(asset.clone(), beneficiary.clone())
		.build();
	assert_eq!(
		message,
		Xcm(vec![
			ReceiveTeleportedAsset(asset.clone().into()),
			BuyExecution { fees: asset.clone(), weight_limit: Unlimited },
			DepositAsset { assets: asset.into(), beneficiary },
		])
	);
}

#[test]
fn default_builder_requires_buy_execution() {
	let asset: Asset = (Here, 100u128).into();
	let beneficiary: Location = AccountId32 { id: [0u8; 32], network: None }.into();
	// This is invalid, since it doesn't pay for fees.
	// This is enforced by the runtime, because the build() method doesn't exist
	// on the resulting type.
	// let message: Xcm<()> = Xcm::builder()
	//     .withdraw_asset(asset.clone().into())
	//     .deposit_asset(asset.into(), beneficiary)
	//     .build();

	// To be able to do that, we need to use the explicitly unpaid variant
	let message: Xcm<()> = Xcm::builder_unpaid()
		.unpaid_execution(Unlimited, None)
		.withdraw_asset(asset.clone())
		.deposit_asset(asset.clone(), beneficiary.clone())
		.build(); // This works
	assert_eq!(
		message,
		Xcm(vec![
			UnpaidExecution { weight_limit: Unlimited, check_origin: None },
			WithdrawAsset(asset.clone().into()),
			DepositAsset { assets: asset.clone().into(), beneficiary: beneficiary.clone() },
		])
	);

	// The other option doesn't have any limits whatsoever, so it should
	// only be used when you really know what you're doing.
	let message: Xcm<()> = Xcm::builder_unsafe()
		.withdraw_asset(asset.clone())
		.deposit_asset(asset.clone(), beneficiary.clone())
		.build();
	assert_eq!(
		message,
		Xcm(vec![
			WithdrawAsset(asset.clone().into()),
			DepositAsset { assets: asset.clone().into(), beneficiary },
		])
	);
}

#[test]
fn default_builder_allows_clear_origin_before_buy_execution() {
	let asset: Asset = (Here, 100u128).into();
	let beneficiary: Location = [0u8; 32].into();
	let message: Xcm<()> = Xcm::builder()
		.receive_teleported_asset(asset.clone())
		.clear_origin()
		.buy_execution(asset.clone(), Unlimited)
		.deposit_asset(asset.clone(), beneficiary.clone())
		.build();
	assert_eq!(
		message,
		Xcm(vec![
			ReceiveTeleportedAsset(asset.clone().into()),
			ClearOrigin,
			BuyExecution { fees: asset.clone(), weight_limit: Unlimited },
			DepositAsset { assets: asset.into(), beneficiary },
		])
	);
}

#[test]
fn bounded_vecs_use_vecs_and_truncate_them() {
	let claimer = Location::parent();
	// We can use a vec instead of a bounded vec for specifying hints.
	let xcm: Xcm<()> = Xcm::builder_unsafe()
		.set_hints(vec![AssetClaimer { location: claimer.clone() }])
		.build();
	assert_eq!(
		xcm,
		Xcm(vec![SetHints {
			hints: BoundedVec::<Hint, HintNumVariants>::truncate_from(vec![AssetClaimer {
				location: Location::parent()
			},]),
		},])
	);

	// If we include more than the limit they'll get truncated.
	let xcm: Xcm<()> = Xcm::builder_unsafe()
		.set_hints(vec![
			AssetClaimer { location: claimer.clone() },
			AssetClaimer { location: Location::here() },
		])
		.build();
	assert_eq!(
		xcm,
		Xcm(vec![SetHints {
			hints: BoundedVec::<Hint, HintNumVariants>::truncate_from(vec![AssetClaimer {
				location: Location::parent()
			},]),
		},])
	);

	let xcm: Xcm<()> = Xcm::builder()
		.withdraw_asset((Here, 100u128))
		.set_hints(vec![AssetClaimer { location: claimer }])
		.clear_origin()
		.pay_fees((Here, 10u128))
		.deposit_asset(All, [0u8; 32])
		.build();
	assert_eq!(
		xcm,
		Xcm(vec![
			WithdrawAsset(Asset { id: AssetId(Location::here()), fun: Fungible(100) }.into()),
			SetHints {
				hints: BoundedVec::<Hint, HintNumVariants>::truncate_from(vec![AssetClaimer {
					location: Location::parent()
				}])
			},
			ClearOrigin,
			PayFees { asset: Asset { id: AssetId(Location::here()), fun: Fungible(10) } },
			DepositAsset {
				assets: All.into(),
				beneficiary: AccountId32 { id: [0u8; 32], network: None }.into()
			},
		])
	);
}

#[test]
fn generated_dispatch_covers_representative_variant_shapes() {
	fn assert_get_weight_impl<T: GetWeight<MacroTestWeightInfo>>() {}
	assert_get_weight_impl::<MacroTestInstruction<()>>();

	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::ClearOrigin),
		Weight::from_parts(11, 11)
	);

	let tuple_assets: Assets = (Here, 1u128).into();
	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::WithdrawAsset(
			tuple_assets,
		)),
		Weight::from_parts(102, 102)
	);

	let named_assets: Assets = (Here, 1u128).into();
	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::TransferAsset {
			assets: named_assets,
			beneficiary: Here.into(),
		}),
		Weight::from_parts(211, 211)
	);

	assert_eq!(
		GetWeight::<MacroTestWeightInfo>::weight(&MacroTestInstruction::<()>::SetAppendix(Xcm(
			vec![ClearOrigin],
		))),
		Weight::from_parts(301, 301)
	);
}
